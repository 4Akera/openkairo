#!/usr/bin/env python3
"""Generate code rows from the composer's catalog (src/core/screens/visit/catalog/data.ts):
- openCare's own local systems (allergens, allergy classes with their cross rules, reactions) → printed for the base codes migration;
- the demo subset of licensed systems (WHO ICD-10 terms, WHO ATC drugs) → supabase/seeds/codes.sql (local demo only; an installation
  loads the full files with scripts/import-codes.sh)."""
import json, re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'src/core/screens/visit/catalog/data.ts')).read()
def block(name):
    start = src.index('export const %s' % name)
    text = src[src.index('= ', start) + 2:]
    text = re.sub(r'^\[\s*//[^\n]*', '[', text)
    depth, i, instr = 0, 0, False
    while True:
        ch = text[i]
        if instr:
            if ch == '\\': i += 1
            elif ch == '"': instr = False
        elif ch == '"': instr = True
        elif ch == '[': depth += 1
        elif ch == ']':
            depth -= 1
            if depth == 0: break
        i += 1
    return json.loads(re.sub(r',\s*\]$', ']', text[:i + 1]))
drugs, problems, allergens, reactions, cross = block('DRUGS'), block('PROBLEMS'), block('ALLERGENS'), block('REACTIONS'), block('CROSS')
q = lambda s: "'" + s.replace("'", "''") + "'"
j = lambda o: q(json.dumps(o, ensure_ascii=False))
slug = lambda s: re.sub(r'[^a-z0-9]+', '_', s.lower()).strip('_')
def local():
    out = ['-- generated by scripts/gen-codes.py from the composer catalog: allergens, allergy classes (with cross rules), reactions']
    rows = []
    for a in allergens:
        rows.append(f"('local.allergen', {q(slug(a['name']))}, {j({'en': a['name']})}, {j({'allergy_class': a['allergy_class'], 'kind': a['kind'], 'synonyms': a['synonyms']})})")
    classes = sorted({a['allergy_class'] for a in allergens if a['allergy_class']} | {d['allergy_class'] for d in drugs if d['allergy_class']} | {c['allergy_class'] for c in cross} | {x for c in cross for x in c['also']})
    for c in classes:
        rules = [{'also': r['also'], 'level': r['level'], 'note': r['note']} for r in cross if r['allergy_class'] == c]
        rows.append(f"('local.allergy-class', {q(c)}, {j({'en': c.replace('_', ' ')})}, {j({'rules': rules})})")
    for r in reactions:
        rows.append(f"('local.reaction', {q(slug(r))}, {j({'en': r})}, '{{}}')")
    out.append('insert into core.codes (system, code, labels, props) values\n  ' + ',\n  '.join(rows) + ';')
    return '\n'.join(out)
def demo():
    out = ['-- demo subset of licensed code systems, generated by scripts/gen-codes.py from the composer catalog (local demo only).',
           '-- An installation loads the full WHO ICD-10 and ATC files with scripts/import-codes.sh.']
    seen, rows = set(), []
    for p in problems:
        if p['icd10'] in seen: continue
        seen.add(p['icd10'])
        rows.append(f"('icd10', {q(p['icd10'])}, {j({'en': p['name']})}, {j({'chronic': p['chronic']})})")
    for d in drugs:
        if d['atc'] in seen: continue
        seen.add(d['atc'])
        rows.append(f"('atc', {q(d['atc'])}, {j({'en': d['name']})}, {j({'allergy_class': d['allergy_class'], 'group': d['group'], 'route': d['route'], 'unit': d['unit']})})")
    out.append('insert into core.codes (system, code, labels, props) values\n  ' + ',\n  '.join(rows) + '\non conflict (system, code) do nothing;')
    return '\n'.join(out)
if sys.argv[1:] == ['local']: print(local())
else:
    open(os.path.join(ROOT, 'supabase/seeds/codes.sql'), 'w').write(demo() + '\n')
    print('wrote supabase/seeds/codes.sql')

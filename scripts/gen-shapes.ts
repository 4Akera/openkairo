// The declared shapes as client types (spec/openCare.md §3.7–§3.8, §8): the client's entry and setting data cannot drift from the
// server silently. Reads the local database read-only (core.types, core.setting_keys; the datatypes are inlined in every shape under
// $defs) and writes src/core/db/shapes.generated.ts. `--check` writes nothing and exits 1 when the file on disk is stale
// (scripts/db-test.sh runs it after the suites). A small JSON Schema → TypeScript converter for the subset the shapes use; a
// keyword it does not know stops the run, so a new kind of shape cannot turn silently into `unknown`.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

type Schema = { [k: string]: unknown }
const OUT = fileURLToPath(new URL('../src/core/db/shapes.generated.ts', import.meta.url))
const HEADER = '// generated by npm run gen:shapes — do not edit'
// keywords that only narrow a value TypeScript cannot narrow (formats, patterns, bounds): left to the writer's shape check
const IGNORED = new Set(['format', 'pattern', 'minLength', 'maxLength', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf',
  'minItems', 'maxItems', 'uniqueItems', 'minProperties', 'maxProperties', 'title', 'description', 'default', 'examples', '$comment'])
const TYPED = new Set(['type', 'properties', 'required', 'additionalProperties', 'items', 'enum', 'const', 'anyOf', 'oneOf', 'allOf', '$ref'])

// ── the database, read-only ──
function query<T>(sql: string): T {
  const db = execFileSync('docker', ['ps', '--format', '{{.Names}}'], { encoding: 'utf8' }).split('\n').find((n) => /^supabase_db_/.test(n))
  if (!db) throw new Error('no supabase_db container is running (supabase start)')
  const out = execFileSync('docker', ['exec', '-i', db, 'psql', '-U', 'postgres', '-At', '-v', 'ON_ERROR_STOP=1',
    '-c', 'set default_transaction_read_only = on', '-c', sql], { encoding: 'utf8', maxBuffer: 64 << 20 })
  return JSON.parse(out.trim().split('\n').pop()!) as T
}
interface Declared { types: { key: string; version: number; layer: string; shape: Schema }[]; settings: { key: string; layer: string; owner_kind: string; many: boolean; shape: Schema }[] }

// ── names ──
const pascal = (key: string) => key.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const prop = (k: string) => /^[A-Za-z_$][\w$]*$/.test(k) ? k : quote(k)
const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const literal = (v: unknown) => typeof v === 'string' ? quote(v) : JSON.stringify(v)
const byCode = (a: string, b: string) => a < b ? -1 : a > b ? 1 : 0   // not localeCompare: the same file on every machine
const sortedKeys = (o: object) => Object.keys(o).sort(byCode)

// ── JSON Schema → TypeScript ──
interface At { depth: number; inline: boolean; where: string }
const pad = (n: number) => '  '.repeat(n)
const nest = (at: At, where: string): At => ({ ...at, depth: at.depth + 1, where })
/** the operators outside every bracket and quote: '|', '&', and whether the whole type is one {…} */
function outer(t: string) {
  let depth = 0; let q = false; const ops = new Set<string>(); let closedAt = -1
  for (let i = 0; i < t.length; i++) {
    const c = t[i]
    if (q) { if (c === '\\') i++; else if (c === "'") q = false; continue }
    if (c === "'") q = true
    else if ('{[(<'.includes(c)) depth++
    else if ('}])>'.includes(c)) { depth--; if (depth === 0 && closedAt < 0) closedAt = i }
    else if (depth === 0 && (c === '|' || c === '&') && t[i - 1] === ' ') ops.add(c)
  }
  return { ops, object: t.startsWith('{') && closedAt === t.length - 1 }
}
const group = (t: string) => outer(t).ops.size ? `(${t})` : t
const union = (ts: string[]) => [...new Set(ts)].join(' | ') || 'never'
function ref(r: unknown, where: string) {
  const m = typeof r === 'string' ? /^#\/\$defs\/([A-Za-z0-9_]+)$/.exec(r) : null
  if (!m) throw new Error(`${where}: only #/$defs/… references are supported, not ${String(r)}`)
  return pascal(m[1])
}
function members(ms: string[], at: At) {
  if (!ms.length) return 'Record<string, never>'
  return at.inline ? `{ ${ms.join('; ')} }` : `{\n${ms.map((m) => pad(at.depth + 1) + m).join('\n')}\n${pad(at.depth)}}`
}
function objectType(s: Schema, at: At): string {
  const props = (s.properties ?? {}) as Record<string, Schema>; const required = new Set((s.required as string[] | undefined) ?? [])
  const extra = s.additionalProperties
  const rest = extra === undefined || extra === true ? 'unknown' : extra === false ? null : ts(extra as Schema, nest(at, `${at.where}.*`))
  if (!Object.keys(props).length && rest) return `Record<string, ${rest}>`
  const ms = sortedKeys(props).map((k) => `${prop(k)}${required.has(k) ? '' : '?'}: ${ts(props[k], nest(at, `${at.where}.${k}`))}`)
  return members(rest ? [...ms, `[key: string]: ${rest}`] : ms, at)
}
function single(t: string, s: Schema, at: At): string {
  switch (t) {
    case 'object': return objectType(s, at)
    case 'array': return `${group(s.items ? ts(s.items as Schema, { ...at, where: `${at.where}[]` }) : 'unknown')}[]`
    case 'string': return 'string'
    case 'integer': case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    default: throw new Error(`${at.where}: unknown type ${t}`)
  }
}
/** one schema node as a TypeScript type; `anyOf` branches that only name more required keys (a note: text or attachments) require them */
function ts(s: Schema, at: At): string {
  for (const k of Object.keys(s)) if (!TYPED.has(k) && !IGNORED.has(k) && !(k === '$defs' && at.depth === 0)) throw new Error(`${at.where}: unsupported keyword ${k}`)
  if (s.$ref) return ref(s.$ref, at.where)
  if ('const' in s) return literal(s.const)
  if (s.enum) return union((s.enum as unknown[]).map(literal))
  const types = Array.isArray(s.type) ? s.type as string[] : s.type ? [s.type as string] : s.properties || s.additionalProperties !== undefined ? ['object'] : []
  const parts = types.length ? [union(types.map((t) => single(t, s, at)))] : []
  for (const k of ['anyOf', 'oneOf'] as const) if (s[k]) parts.push(union((s[k] as Schema[]).map((b, i) => branch(s, b, { ...at, inline: true, where: `${at.where}.${k}[${i}]` }))))
  if (s.allOf) parts.push(...(s.allOf as Schema[]).map((b, i) => ts(b, { ...at, where: `${at.where}.allOf[${i}]` })))
  return !parts.length ? 'unknown' : parts.length === 1 ? parts[0] : parts.map(group).join(' & ')
}
function branch(parent: Schema, b: Schema, at: At) {
  if (!Object.keys(b).every((k) => k === 'required')) return ts(b, at)
  const props = (parent.properties ?? {}) as Record<string, Schema>
  for (const k of b.required as string[]) if (!props[k]) throw new Error(`${at.where}: requires ${k}, which the shape does not name`)
  return members((b.required as string[]).map((k) => `${prop(k)}: ${ts(props[k], nest(at, `${at.where}.${k}`))}`), at)
}
const declare = (name: string, s: Schema, doc: string) => {
  const t = ts(s, { depth: 0, inline: false, where: name })
  return `/** ${doc} */\n${outer(t).object ? `export interface ${name} ${t}` : `export type ${name} = ${t}`}`
}

// ── the file ──
function generate(d: Declared): string {
  const defs = new Map<string, string>()
  for (const x of [...d.types, ...d.settings]) for (const [k, v] of Object.entries((x.shape.$defs ?? {}) as Record<string, Schema>)) {
    const was = defs.get(k); const now = JSON.stringify(v)
    if (was !== undefined && was !== now) throw new Error(`the datatype ${k} differs between shapes (${x.key})`)
    defs.set(k, now)
  }
  const names = new Map<string, string>()
  const claim = (name: string, what: string) => { const was = names.get(name); if (was) throw new Error(`${name} names both ${was} and ${what}`); names.set(name, what); return name }
  const out = [HEADER, '// The declared shapes (spec/openCare.md §3.7–§3.8) as types: the datatypes, each entry type\'s data, each setting\'s data.', '']
  out.push('// ── datatypes (core.datatypes) ──')
  for (const k of [...defs.keys()].sort(byCode)) out.push(declare(claim(pascal(k), `datatype ${k}`), JSON.parse(defs.get(k)!) as Schema, `datatype ${k}`))
  out.push('', '// ── entry types (core.types): data by type, the latest version under the key\'s own name ──')
  const byKey = new Map<string, Declared['types']>()
  for (const t of [...d.types].sort((a, b) => byCode(a.key, b.key) || a.version - b.version)) byKey.set(t.key, [...(byKey.get(t.key) ?? []), t])
  const entryNames: [string, string][] = []
  for (const [key, vs] of byKey) {
    const name = pascal(key); const latest = vs[vs.length - 1]
    if (vs.length === 1) out.push(declare(claim(name, `type ${key}`), latest.shape, `${key} v${latest.version} (${latest.layer})`))
    else {
      for (const v of vs) out.push(declare(claim(`${name}V${v.version}`, `type ${key} v${v.version}`), v.shape, `${key} v${v.version} (${v.layer})`))
      out.push(`/** ${key}: the latest version, what the client writes */\nexport type ${claim(name, `type ${key}`)} = ${name}V${latest.version}`)
    }
    entryNames.push([key, name])
  }
  out.push('', '// ── settings (core.setting_keys) ──')
  const settingNames: [string, string][] = []
  for (const st of [...d.settings].sort((a, b) => byCode(a.key, b.key))) {
    const name = claim(`${pascal(st.key)}Setting`, `setting ${st.key}`)
    out.push(declare(name, st.shape, `setting ${st.key} (${st.layer}; owner ${st.owner_kind}${st.many ? ', many' : ''})`)); settingNames.push([st.key, name])
  }
  out.push('', '/** each entry type\'s data, by its key */', `export interface EntryData {\n${entryNames.map(([k, n]) => `  ${quote(k)}: ${n}`).join('\n')}\n}`)
  out.push('/** each setting\'s data, by its key */', `export interface SettingData {\n${settingNames.map(([k, n]) => `  ${quote(k)}: ${n}`).join('\n')}\n}`, '')
  return out.join('\n')
}

const rel = 'src/core/db/shapes.generated.ts'
try {
  const declared = query<Declared>(`select json_build_object(
    'types', (select coalesce(json_agg(json_build_object('key', key, 'version', version, 'layer', layer, 'shape', shape) order by key, version), '[]') from core.types),
    'settings', (select coalesce(json_agg(json_build_object('key', key, 'layer', layer, 'owner_kind', owner_kind, 'many', many, 'shape', shape) order by key), '[]') from core.setting_keys))`)
  const text = generate(declared); const counts = `${declared.types.length} type versions, ${declared.settings.length} settings`
  if (process.argv.includes('--check')) {
    let now = ''; try { now = readFileSync(OUT, 'utf8') } catch { /* missing is stale */ }
    if (now !== text) { console.log(`✗ ${rel} is stale: the declared shapes changed; run npm run gen:shapes`); process.exit(1) }
    console.log(`✓ ${rel} (${counts})`)
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${rel} (${counts})`)
  }
} catch (e) {
  console.log(`✗ gen:shapes: ${e instanceof Error ? e.message.split('\n')[0] : String(e)}`); process.exit(1)
}

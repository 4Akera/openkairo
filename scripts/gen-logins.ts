// The sign-in page's demo logins from one source of truth (spec/openCare.md §5.1 rule 9): the people the seeds make
// (supabase/seeds/*.sql, through the demo kit) in the demo clinic, each with the role they hold and grouped by the department they
// hold it in (held everywhere first), and their one password (the kit's demo.password()), written to
// src/core/shell/logins.generated.ts. Reads the local database read-only, like gen-shapes. `--check` writes nothing and exits 1
// when the file on disk is stale (scripts/db-test.sh runs it after the suites).
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const OUT = fileURLToPath(new URL('../src/core/shell/logins.generated.ts', import.meta.url))
const HEADER = '// generated by npm run gen:logins — do not edit'
const CLINIC = '00000000-0000-0000-0000-00000000a001'   // the base seed's clinic (supabase/seeds/demo_kit.sql, demo.base('clinic'))

interface Person { email: string; name: string; role: string }
interface Group { department: string; department_id: string | null; people: Person[] }

function query<T>(sql: string): T {
  const db = execFileSync('bash', ['scripts/db-container.sh'], { encoding: 'utf8' }).trim()   // this checkout's own stack
  if (!db) throw new Error('no supabase_db container is running (supabase start)')
  const out = execFileSync('docker', ['exec', '-i', db, 'psql', '-U', 'postgres', '-At', '-v', 'ON_ERROR_STOP=1',
    '-c', 'set default_transaction_read_only = on', '-c', sql], { encoding: 'utf8', maxBuffer: 16 << 20 })
  return JSON.parse(out.trim().split('\n').pop()!) as T
}

const groups = query<Group[]>(`
  with h as (
    select u.name, a.email::text as email, r.name as role, h.department_id
      from core.users u join auth.users a on a.id = u.login_id
      join core.live_holdings(u.organization_id) h on h.user_id = u.id join core.roles r on r.id = h.role_id
     where u.organization_id = '${CLINIC}' and u.kind = 'staff' and u.retired_at is null)
  select coalesce(json_agg(json_build_object('department', g.department, 'department_id', g.department_id, 'people', g.people)
                           order by g.position nulls first, g.department), '[]')
    from (select h.department_id, coalesce(d.name, 'Everywhere') as department, d.position,
                 json_agg(json_build_object('email', h.email, 'name', h.name, 'role', h.role) order by h.role, h.name) as people
            from h left join core.departments d on d.organization_id = '${CLINIC}' and d.id = h.department_id
           group by h.department_id, d.name, d.position) g`)

const password = query<string>(`select to_json(demo.password())`)

const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const lines = [HEADER,
  '/** The demo logins\' one password: the kit\'s demo.password() (supabase/seeds/demo_kit.sql). */',
  `export const DEMO_PASSWORD = ${quote(password)}`,
  '/** The demo\'s people, one at least for every built-in role, grouped by the department they work in (held',
  ' *  everywhere first; a person working in two departments is in both): generated from the seeds, never typed twice (spec §5.1 rule 9). */',
  'export interface DemoLogin { email: string; name: string; role: string }',
  'export interface DemoGroup { department: string; departmentId: string | null; people: DemoLogin[] }',
  'export const DEMO_GROUPS: DemoGroup[] = [',
  ...groups.map((g) => `  { department: ${quote(g.department)}, departmentId: ${g.department_id ? quote(g.department_id) : 'null'}, people: [\n` +
    g.people.map((p) => `    { email: ${quote(p.email)}, name: ${quote(p.name)}, role: ${quote(p.role)} },`).join('\n') + '\n  ] },'),
  ']', '']
const text = lines.join('\n')

if (process.argv.includes('--check')) {
  let now = ''
  try { now = readFileSync(OUT, 'utf8') } catch { /* missing */ }
  if (now !== text) { console.error('src/core/shell/logins.generated.ts is stale: run npm run gen:logins'); process.exit(1) }
} else {
  writeFileSync(OUT, text)
  console.log(`logins: ${groups.length} departments, ${new Set(groups.flatMap((g) => g.people.map((p) => p.email))).size} people`)
}
